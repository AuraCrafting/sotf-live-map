"""Writes web/data/items.js: which map locations are which game item (the "additem" id).

The map uses it to mark an item found when your save's inventory has it and the item has only one
spot on the map (a radio or a battery could come from anywhere, the Modern Axe only from one place).

    python -I tools/build_items.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
upstream = json.load(open(os.path.join(ROOT, 'tools', 'upstream_locations.json'), encoding='utf-8'))
s = open(os.path.join(ROOT, 'web', 'data', 'locations.js'), encoding='utf-8').read()
m = re.search(r'window\.SOTF_LOCATIONS\s*=\s*', s)
ours = {l['id'] for l in json.JSONDecoder().raw_decode(s[m.end():])[0]}

items = {}
for n in upstream:
    raw = n.get('itemId') or n.get('itemid')
    hit = re.search(r'\d+', str(raw or ''))
    if hit and n['id'] in ours:
        items[str(n['id'])] = int(hit.group())

out = os.path.join(ROOT, 'web', 'data', 'items.js')
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/build_items.py from the upstream location data. Do not edit by hand.\n')
    f.write('// Map location id -> the game\'s item id.\n')
    f.write('window.SOTF_ITEMS = ' + json.dumps(items, separators=(',', ':')) + ';\n')
print(f'{len(items)} locations with an item id -> {out}')
